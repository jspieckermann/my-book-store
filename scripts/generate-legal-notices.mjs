#!/usr/bin/env node
// Regenerates src/app/legal/legal-notices-data.ts from the resolved production
// dependency tree (`npm ls --all --omit=dev --json`) and each package's own
// package.json `license` field. Never hand-edit the output file — run
// `npm run legal` instead. See openspec/changes/add-legal-page/design.md.

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUTPUT_PATH = 'src/app/legal/legal-notices-data.ts';

function collectDependencies(node, found) {
  if (!node?.dependencies) return;
  for (const [name, entry] of Object.entries(node.dependencies)) {
    if (entry?.version) {
      found.set(`${name}@${entry.version}`, { name, version: entry.version });
    }
    collectDependencies(entry, found);
  }
}

function readLicense(name, version) {
  try {
    const pkgJsonPath = join('node_modules', ...name.split('/'), 'package.json');
    const pkg = JSON.parse(readFileSync(pkgJsonPath, 'utf8'));
    if (typeof pkg.license === 'string' && pkg.license.trim()) {
      return pkg.license.trim();
    }
    if (Array.isArray(pkg.licenses) && pkg.licenses[0]?.type) {
      return pkg.licenses[0].type;
    }
    return 'Unknown';
  } catch {
    return 'Unknown';
  }
}

function main() {
  const raw = execSync('npm ls --all --omit=dev --json', {
    encoding: 'utf8',
    maxBuffer: 1024 * 1024 * 10,
  });
  const tree = JSON.parse(raw);

  const found = new Map();
  collectDependencies(tree, found);

  const notices = [...found.values()]
    .map(({ name, version }) => ({ name, version, license: readLicense(name, version) }))
    .sort((a, b) => a.name.localeCompare(b.name));

  const lines = notices.map(
    (n) => `  { name: ${JSON.stringify(n.name)}, version: ${JSON.stringify(n.version)}, license: ${JSON.stringify(n.license)} },`,
  );

  const output = `// Auto-generated by \`npm run legal\` — do not hand-edit. See
// openspec/changes/add-legal-page/design.md for how this is produced.

export interface LegalNotice {
  name: string;
  version: string;
  license: string;
}

export const LEGAL_NOTICES: LegalNotice[] = [
${lines.join('\n')}
];
`;

  writeFileSync(OUTPUT_PATH, output);
  console.log(`✓ Wrote ${OUTPUT_PATH} — ${notices.length} production dependencies`);
}

main();
